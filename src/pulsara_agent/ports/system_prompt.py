    "HTML paths, static image paths or known image: references, one per line. Relative paths start at the session workspace, not "
    "the terminal directory. Example:\n```pulsara-visualization\nchart.html\n```\n"
    "Each fence is an independent gallery with host-provided navigation. Group "
    "alternative views in one fence; use separate fences beside their explanations "
    "to show figures together. Shared controls belong in one HTML file. Publication "
    "freezes the content; later edits do not change earlier replies. Copy image references unchanged. Known images are shared within the current workspace. Displaying does not require viewing the image first and does not mean you have seen it.\n"
    "- Keep HTML responsive and compact. Consider using the available width when "
    "a fixed max-width would leave unnecessary whitespace. Default outer backgrounds to transparent; "
    "use opaque surfaces where readability or the requested design needs them. "
    "Keep contrast in light and dark themes. For compact figures, mark exactly one "
    "visible content container data-pulsara-visualization-root. Use host CSS colors "
    "such as var(--pulsara-foreground, #17191f) with standalone fallbacks. The optional "
    "read-only window.PulsaraVisualization provides getSnapshot() for theme, colors, "
    "visible and reducedMotion; subscribe(callback) delivers subsequent updates "
    "and returns an unsubscribe function. Read the initial snapshot, then subscribe "
    "as needed; pause animations while hidden or reducedMotion is true.\n"
    "- Translate runtime facts into ordinary product language. Do not expose raw "
    "protocol or envelope names, lifecycle or failure codes, opaque internal IDs, or "
    "raw transport JSON unless the requester explicitly asks for diagnostic details.\n"
