def choose_agent_name(used_names: Collection[str]) -> str:
    """Prefer unused names within a ROOT; exhausting the pool never blocks work."""
    used = set(used_names)
    available = tuple(name for name in SCIENTIST_NAMES if name not in used)
    return choice(available or SCIENTIST_NAMES)
