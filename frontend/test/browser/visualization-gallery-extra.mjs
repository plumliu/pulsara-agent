export default async function checkExtra(page, url, outputDir) {
const context=page.context();
const network=[],popups=[],errors=[];
page.on('request',r=>{if(r.url().startsWith('https://example.invalid'))network.push(r.url())});
context.on('page',p=>popups.push(p));page.on('pageerror',e=>errors.push(String(e)));
const results=[];const check=(ok,label)=>{if(!ok)throw new Error(label);results.push(label)};

await page.goto(url);
await page.getByRole('button',{name:'展开可视化图集'}).click();
const inner=()=>page.frameLocator('.is-active iframe').frameLocator('iframe');
await inner().getByRole('heading').waitFor();
await page.waitForTimeout(250);
check(await page.locator('.is-active').evaluate(el=>getComputedStyle(el).animationName)==='none','reduced motion respected');
await page.getByRole('button',{name:'放大可视化',exact:true}).click();
await page.waitForTimeout(200);
let rect=await page.locator('dialog').boundingBox();check(rect.x>=0&&rect.x+rect.width<=390,'touch modal fits narrow screen');
check(await page.getByRole('button',{name:'退出放大',exact:true}).evaluate(el=>el.offsetWidth>=44),'touch controls have 44px targets');
await inner().getByRole('textbox',{name:'图内筛选'}).fill('modal retained');
await page.getByRole('button',{name:'退出放大',exact:true}).click();
check(await inner().getByRole('textbox',{name:'图内筛选'}).inputValue()==='modal retained','modal editing preserved after close');
await page.getByRole('button',{name:'查看可视化 6',exact:true}).click();
await inner().getByRole('heading',{name:'高密度表格'}).waitFor();
check(await inner().locator('tr').count()===2500,'2500-row document renders');
await inner().locator('body').evaluate(()=>scrollTo(0,1000000));
check(await inner().locator('tr').last().evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight+1),'last row accessible');
await page.getByRole('button',{name:'查看可视化 8',exact:true}).click();
await inner().getByText('DOM 隔离生效').waitFor();
await inner().getByRole('link',{name:'顶层导航'}).click();
check(page.url()===url,'untrusted top navigation blocked');
check(network.length===0&&popups.length===0,'network and popup sandbox boundaries preserved');
await page.getByRole('button',{name:'查看可视化 7',exact:true}).click();
await inner().locator('#root').waitFor();
await inner().locator('#root').evaluate(el=>{el.style.height='1200px'});
await page.locator('.is-active[data-visualization-layout="page"]').waitFor();
check(await inner().locator('body').evaluate(el=>el.scrollHeight>=1200),'growing root restores scrollable page');
await page.getByRole('button',{name:'查看可视化 1',exact:true}).click();
await page.evaluate(()=>document.documentElement.dataset.theme='dark');
await page.setViewportSize({width:1280,height:900});
await page.waitForTimeout(250);
await page.screenshot({path:outputDir + '/gallery-dark.png'});
await page.getByRole('button',{name:'放大可视化',exact:true}).click();
await page.waitForTimeout(200);
await page.screenshot({path:outputDir + '/gallery-fullscreen-settled.png'});
check(await page.locator('.is-active iframe').evaluate(el=>Math.abs(el.clientWidth-el.closest('.visualization-gallery__stage').clientWidth)<=1),'modal HTML viewport grows with modal');
await page.mouse.click(2,2);
check(!await page.locator('dialog').evaluate(el=>el.matches(':modal')),'backdrop click exits enlarged view');
check(errors.length===0,'no unhandled page errors');

return {checks:results,network,popups:popups.length,errors};
}
