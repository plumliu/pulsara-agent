export default async function checkGallery(page, url, outputDir) {
  const results = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
  await page.setViewportSize({width:1280,height:900});
  await page.goto(url);
  await page.getByRole('button',{name:'展开可视化图集'}).waitFor();
  check(await page.getByRole('button',{name:'展开可视化图集'}).textContent().then(text=>text.includes('可视化 · 共 10 张')),'header names the total explicitly');
  check(await page.locator('.assistant-visualization iframe').count()===0,'collapsed has no live HTML');
  await page.getByRole('button',{name:'展开可视化图集'}).click();
  const inner=()=>page.frameLocator('.visualization-gallery__page.is-active iframe').frameLocator('iframe');
  await inner().getByRole('heading',{name:'群体结构 · 响应式视图'}).waitFor();
  await inner().getByRole('textbox',{name:'图内筛选'}).fill('保留筛选');
  await inner().getByRole('button',{name:'点击 0'}).click();
  await page.locator('.visualization-gallery__strip img').first().waitFor();
  const title = page.locator('.visualization-gallery__toolbar > span');
  check(await title.textContent() === await title.getAttribute('title'),'full filename is available on hover');
  check(await title.textContent() === await page.locator('.visualization-gallery__strip > button > span:last-child').first().textContent(),'main and thumbnail use the same subscribed filename');
  await page.waitForTimeout(250);
  await page.screenshot({path:outputDir + '/gallery-desktop.png'});
  await page.waitForTimeout(250);
  const h=(await page.locator('.visualization-gallery__stage').boundingBox()).height;
  const original=await page.locator('.is-active iframe').elementHandle();
  await page.getByRole('button',{name:'下一张可视化'}).click();
  await inner().getByRole('heading',{name:'6000px 宽图'}).waitFor();
  check(await inner().locator('body').evaluate(el=>el.scrollWidth>=6000),'wide document remains scrollable');
  await inner().locator('body').evaluate(()=>scrollTo(6000,0));
  await page.screenshot({path:outputDir + '/gallery-wide-scrolled.png'});
  await page.getByRole('button',{name:'下一张可视化'}).click();
  await inner().getByRole('heading',{name:'10000px 长报告'}).waitFor();
  await inner().locator('body').evaluate(()=>scrollTo(0,11000));
  check(await inner().locator('body').evaluate(()=>scrollY>9000),'long page reaches its end');
  check(Math.abs((await page.locator('.visualization-gallery__stage').boundingBox()).height-h)<1,'unequal documents have stable viewport height');
  await page.screenshot({path:outputDir + '/gallery-tall-scrolled.png'});
  await page.getByRole('button',{name:'查看可视化 1',exact:true}).click();
  check(await original.evaluate(el=>el.isConnected && el.closest('.is-active')!==null),'recent page keeps same iframe');
  check(await inner().getByRole('textbox',{name:'图内筛选'}).inputValue()==='保留筛选','switch preserves filter');
  await inner().getByRole('button',{name:'点击 1'}).waitFor();
  await page.getByRole('button',{name:'放大可视化',exact:true}).click();
  check(await page.locator('dialog').evaluate(el=>el.matches(':modal')),'enlarge uses native modal');
  check(await original.evaluate(el=>el.isConnected),'enlarge retains iframe identity');
  await page.waitForTimeout(250);
  await page.screenshot({path:outputDir + '/gallery-fullscreen.png'});
  await page.keyboard.press('Escape');
  check(!await page.locator('dialog').evaluate(el=>el.matches(':modal')),'Escape closes modal');
  check(await page.getByRole('button',{name:'放大可视化',exact:true}).evaluate(el=>el===document.activeElement),'focus returns to enlarge button');
  await page.getByRole('button',{name:'收起可视化图集'}).click();
  await page.getByRole('button',{name:'展开可视化图集'}).click();
  check(await inner().getByRole('textbox',{name:'图内筛选'}).inputValue()==='保留筛选','collapse preserves input');
  await page.getByRole('button',{name:'查看可视化 4',exact:true}).click();
  await page.locator('.is-active[data-visualization-layout="root"]').waitFor();
  check(Math.abs((await page.locator('.visualization-gallery__stage').boundingBox()).height-h)<1,'small root does not shrink gallery');
  await page.screenshot({path:outputDir + '/gallery-small-root.png'});
  await page.getByRole('button',{name:'查看可视化 5',exact:true}).click();
  await inner().getByText('底部始终可见').waitFor();
  check(await inner().locator('footer').evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight+1),'vh layout footer fits actual viewport');
  for(const size of [{width:320,height:640},{width:390,height:844},{width:640,height:280},{width:2560,height:1440}]) {
    await page.setViewportSize(size);
    await page.waitForTimeout(250);
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`no outer horizontal overflow ${size.width}x${size.height}`);
    const b=await page.locator('.assistant-visualization').boundingBox();
    check(b.x>=0 && b.x+b.width<=size.width+1,`gallery fits ${size.width}x${size.height}`);
    if(size.width===320)await page.screenshot({path:outputDir + '/gallery-mobile.png'});
  }
  await page.setViewportSize({width:1280,height:900});
  await page.getByRole('button',{name:'查看可视化 9（无法显示）'}).click();
  await page.getByText('示例文件未能读取',{exact:true}).waitFor();
  await page.getByRole('button',{name:'下一张可视化'}).click();
  await page.getByRole('button',{name:'重试',exact:true}).waitFor();
  check(await page.locator('.visualization-gallery__page iframe').count()<=3,'failed pages do not accumulate frames');
  await page.goto(url + '?count=1000&slow=1');
  await page.getByRole('button',{name:'展开可视化图集'}).click();
  await page.getByRole('button',{name:'查看可视化 1',exact:true}).press('End');
  await page.getByRole('button',{name:'查看可视化 1000',exact:true}).waitFor();
  check(await page.locator('.visualization-gallery__counter').textContent()==='1000 / 1000','1000th artifact reachable by keyboard');
  check(await page.getByRole('button',{name:'下一张可视化'}).isDisabled(),'last item does not loop');
  await page.getByRole('button',{name:'查看可视化 1000',exact:true}).press('Home');
  for(let i=0;i<50;i++) await page.getByRole('button',{name:'下一张可视化'}).click();
  await page.waitForTimeout(500);
  check(await page.locator('.visualization-gallery__page iframe').count()<=3,'50 rapid switches retain at most three pages');
  check(await page.locator('.visualization-gallery__counter').textContent()==='51 / 1000','late HTML does not replace selection');
  check((await page.evaluate(()=>window.galleryReads)).length<70,'1000 artifacts are not eagerly read');
  await page.screenshot({path:outputDir + '/gallery-1000.png'});
  await page.goto(url + '?count=1');
  await page.getByRole('button',{name:'展开可视化图集'}).click();
  check(await page.locator('.visualization-gallery__strip').count()===0,'single artifact hides filmstrip');
  await page.goto(url + '?count=0');
  check(await page.locator('.assistant-visualization').count()===0,'empty group has no control');
  return {passed:results.length,checks:results};
}
